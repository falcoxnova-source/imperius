#!/bin/bash
Q() { docker exec -e PGCLIENTENCODING=UTF8 xnova-database psql -U postgres -d postgres -At -c "$1"; }
echo "== funcs with 'recovered'"
Q "select p.oid::regprocedure from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.prosrc like '%''recovered''%'"
echo "== funcs with 25 USD"
Q "select p.proname||' :: '||l from pg_proc p join pg_namespace n on n.oid=p.pronamespace, regexp_split_to_table(p.prosrc, E'\n') l where n.nspname='public' and p.proname like '%occupation%' and l ~ '25'"
echo "== OCUPA lines in process_acs_fleet_arrival"
Q "select l from pg_proc p, regexp_split_to_table(p.prosrc, E'\n') l where p.proname='process_acs_fleet_arrival' and (l ilike '%occ%')"
echo "== fleet_calc_slowest_speed sig"
Q "select p.oid::regprocedure from pg_proc p where p.proname in ('fleet_calc_slowest_speed','fleet_calc_distance','fleet_calc_flight_time')"
echo "== occupation ship stats"
Q "select id, code, base_speed, cargo_capacity, fuel_consumption from ship_types where code='occupation_ship'"
echo "== occupation_abandon live md5 + try_start consume lines"
Q "select l from pg_proc p, regexp_split_to_table(p.prosrc, E'\n') l where p.proname='_occ_try_start' and (l ilike '%v_occ_qty%' or l ilike '%consume%')"
echo "== occupation_abandon body"
Q "select prosrc from pg_proc where proname='occupation_abandon'"
echo "== purchase price lines"
Q "select l from pg_proc p, regexp_split_to_table(p.prosrc, E'\n') l where p.proname in ('purchase_occupation_ship','get_occupation_ship_info') and (l ~ '25' )"
echo "== ship desc / purchase message"
Q "select l from pg_proc p, regexp_split_to_table(p.prosrc, E'\n') l where p.proname in ('purchase_occupation_ship') and (l ilike '%USD%' or l ilike '%usd%')"
